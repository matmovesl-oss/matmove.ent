type ReceiptField = { label: string; value: unknown };
type ShareReceiptPdfInput = {
  title: string;
  subtitle?: string;
  reference?: string;
  filename: string;
  fields: ReceiptField[];
};

const encoder = new TextEncoder();
const bytes = (value: string) => encoder.encode(value);

function plainText(value: unknown): string {
  return String(value ?? 'Not recorded')
    .replace(/\r\n?/g, '\n')
    .normalize('NFKD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/[^\x20-\x7E\n]/g, ' ');
}

function pdfString(value: string): string {
  return value.replace(/\\/g, '\\\\').replace(/\(/g, '\\(').replace(/\)/g, '\\)');
}

function wrapText(value: string, maxChars = 82): string[] {
  const result: string[] = [];
  for (const originalLine of value.split('\n')) {
    let line = originalLine.trim();
    if (!line) { result.push(' '); continue; }
    while (line.length > maxChars) {
      let cut = line.lastIndexOf(' ', maxChars);
      if (cut < Math.floor(maxChars * 0.55)) cut = maxChars;
      result.push(line.slice(0, cut).trim());
      line = line.slice(cut).trim();
    }
    result.push(line);
  }
  return result;
}

function jpegSize(data: Uint8Array): { width: number; height: number } | null {
  if (data.length < 4 || data[0] !== 0xff || data[1] !== 0xd8) return null;
  let offset = 2;
  while (offset + 4 < data.length) {
    if (data[offset] !== 0xff) { offset++; continue; }
    while (offset < data.length && data[offset] === 0xff) offset++;
    const marker = data[offset++];
    if (marker === 0xd8 || marker === 0xd9 || (marker >= 0xd0 && marker <= 0xd7)) continue;
    if (offset + 2 > data.length) break;
    const length = (data[offset] << 8) | data[offset + 1];
    if (length < 2 || offset + length > data.length) break;
    const isFrame = [0xc0,0xc1,0xc2,0xc3,0xc5,0xc6,0xc7,0xc9,0xca,0xcb,0xcd,0xce,0xcf].includes(marker);
    if (isFrame && length >= 7) {
      return {
        height: (data[offset + 3] << 8) | data[offset + 4],
        width: (data[offset + 5] << 8) | data[offset + 6],
      };
    }
    offset += length;
  }
  return null;
}

async function loadBrandLogo(): Promise<{ data: Uint8Array; width: number; height: number } | null> {
  try {
    const baseUrl = (import.meta as any).env?.BASE_URL || '/';
    const response = await fetch(`${baseUrl}logo.jpg`, { cache: 'force-cache' });
    if (!response.ok) return null;
    const data = new Uint8Array(await response.arrayBuffer());
    const size = jpegSize(data);
    return size ? { data, ...size } : null;
  } catch {
    // Receipt generation remains available if a locally cached logo cannot be fetched.
    return null;
  }
}

function textAt(x: number, y: number, size: number, value: string, font = 'F1', color = '0.12 0.16 0.22') {
  return `BT /${font} ${size} Tf ${color} rg 1 0 0 1 ${x} ${y} Tm (${pdfString(value)}) Tj ET\n`;
}

function makePageContent(args: {
  title: string; subtitle: string; reference: string; fields: ReceiptField[];
  page: number; pageCount: number; logo: { width: number; height: number } | null;
}): string {
  const { title, subtitle, reference, fields, page, pageCount, logo } = args;
  let content = '';
  content += 'q 0.97 0.98 0.99 rg 0 0 612 792 re f Q\n';
  content += 'q 1 1 1 rg 32 32 548 728 re f Q\n';
  if (logo) {
    const box = 46;
    const ratio = logo.width / logo.height;
    const imageW = ratio >= 1 ? box : box * ratio;
    const imageH = ratio >= 1 ? box / ratio : box;
    content += `q ${imageW.toFixed(2)} 0 0 ${imageH.toFixed(2)} 48 ${(727 - imageH / 2).toFixed(2)} cm /Logo Do Q\n`;
  } else {
    content += textAt(48, 738, 17, 'MatMove', 'F2', '0.05 0.25 0.48');
  }
  content += textAt(108, 746, 17, plainText(title).slice(0, 58), 'F2', '0.05 0.17 0.34');
  content += textAt(108, 727, 9, plainText(subtitle).slice(0, 90), 'F1', '0.35 0.39 0.45');
  content += textAt(48, 697, 9, `Reference: ${plainText(reference).slice(0, 90)}`, 'F2', '0.18 0.22 0.28');
  content += '0.86 0.89 0.92 RG 48 683 m 564 683 l S\n';
  let y = 663;
  for (const field of fields) {
    const label = plainText(field.label).replace(/\n/g, ' ').slice(0, 100);
    const lines = wrapText(plainText(field.value));
    content += textAt(48, y, 8, label, 'F2', '0.39 0.43 0.49');
    y -= 14;
    for (const line of lines) {
      content += textAt(48, y, 10, line, 'F1', '0.12 0.16 0.22');
      y -= 13;
    }
    y -= 9;
  }
  content += '0.90 0.92 0.94 RG 48 54 m 564 54 l S\n';
  content += textAt(48, 39, 8, 'Generated by MatMove. Keep this document for your records.', 'F1', '0.42 0.46 0.52');
  content += textAt(520, 39, 8, `${page}/${pageCount}`, 'F1', '0.42 0.46 0.52');
  return content;
}

function concat(parts: Uint8Array[]): Uint8Array {
  const length = parts.reduce((sum, part) => sum + part.length, 0);
  const result = new Uint8Array(length);
  let offset = 0;
  for (const part of parts) { result.set(part, offset); offset += part.length; }
  return result;
}

function buildPdf(input: ShareReceiptPdfInput, logo: Awaited<ReturnType<typeof loadBrandLogo>>): Blob {
  const prepared = input.fields.map((field) => ({
    label: plainText(field.label),
    value: plainText(field.value),
  }));
  const pages: ReceiptField[][] = [];
  let current: ReceiptField[] = [];
  let used = 0;
  const available = 575;
  for (const field of prepared) {
    const rowHeight = 14 + wrapText(String(field.value)).length * 13 + 9;
    if (current.length && used + rowHeight > available) {
      pages.push(current); current = []; used = 0;
    }
    current.push(field); used += rowHeight;
  }
  if (current.length || !pages.length) pages.push(current);

  const catalogId = 1, pagesId = 2, regularFontId = 3, boldFontId = 4;
  const logoId = logo ? 5 : null;
  const firstPageId = logo ? 6 : 5;
  const objects: Uint8Array[] = [];
  const addObject = (id: number, body: Uint8Array) => {
    objects[id] = concat([bytes(`${id} 0 obj\n`), body, bytes('\nendobj\n')]);
  };
  addObject(catalogId, bytes(`<< /Type /Catalog /Pages ${pagesId} 0 R >>`));
  const pageIds = pages.map((_, index) => firstPageId + index * 2);
  addObject(pagesId, bytes(`<< /Type /Pages /Kids [${pageIds.map(id => `${id} 0 R`).join(' ')}] /Count ${pages.length} >>`));
  addObject(regularFontId, bytes('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>'));
  addObject(boldFontId, bytes('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>'));
  if (logo && logoId) {
    const imageHeader = bytes(`<< /Type /XObject /Subtype /Image /Width ${logo.width} /Height ${logo.height} /ColorSpace /DeviceRGB /BitsPerComponent 8 /Filter /DCTDecode /Length ${logo.data.length} >>\nstream\n`);
    addObject(logoId, concat([imageHeader, logo.data, bytes('\nendstream')]));
  }

  pages.forEach((fields, index) => {
    const pageId = pageIds[index];
    const contentId = pageId + 1;
    const content = makePageContent({
      title: input.title,
      subtitle: input.subtitle || 'Trip details from your MatMove account',
      reference: input.reference || 'Not provided',
      fields,
      page: index + 1,
      pageCount: pages.length,
      logo: logo ? { width: logo.width, height: logo.height } : null,
    });
    const contentBytes = bytes(content);
    const resourceLogo = logo ? ` /XObject << /Logo ${logoId} 0 R >>` : '';
    addObject(pageId, bytes(`<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 ${regularFontId} 0 R /F2 ${boldFontId} 0 R >>${resourceLogo} >> /Contents ${contentId} 0 R >>`));
    addObject(contentId, concat([bytes(`<< /Length ${contentBytes.length} >>\nstream\n`), contentBytes, bytes('endstream')]));
  });

  const maxId = Math.max(...Object.keys(objects).map(Number));
  const chunks: Uint8Array[] = [bytes('%PDF-1.4\n%MatMove\n')];
  const offsets = new Array(maxId + 1).fill(0);
  let position = chunks[0].length;
  for (let id = 1; id <= maxId; id++) {
    const objectBytes = objects[id];
    if (!objectBytes) throw new Error(`PDF object ${id} was not created.`);
    offsets[id] = position;
    chunks.push(objectBytes);
    position += objectBytes.length;
  }
  const xrefOffset = position;
  let xref = `xref\n0 ${maxId + 1}\n0000000000 65535 f \n`;
  for (let id = 1; id <= maxId; id++) xref += `${String(offsets[id]).padStart(10, '0')} 00000 n \n`;
  xref += `trailer\n<< /Size ${maxId + 1} /Root ${catalogId} 0 R >>\nstartxref\n${xrefOffset}\n%%EOF`;
  chunks.push(bytes(xref));
  return new Blob(chunks, { type: 'application/pdf' });
}

export async function shareReceiptPdf(input: ShareReceiptPdfInput): Promise<'shared' | 'downloaded'> {
  if (!input || !Array.isArray(input.fields)) throw new Error('Receipt details are missing.');
  const logo = await loadBrandLogo();
  const pdf = buildPdf(input, logo);
  const safeName = (input.filename || 'MatMove-receipt').replace(/[^a-z0-9._-]+/gi, '-').replace(/\.pdf$/i, '') || 'MatMove-receipt';
  const filename = `${safeName}.pdf`;
  const file = new File([pdf], filename, { type: 'application/pdf' });

  if (typeof navigator !== 'undefined' && typeof navigator.share === 'function'
      && typeof navigator.canShare === 'function' && navigator.canShare({ files: [file] })) {
    try {
      await navigator.share({ title: input.title || 'MatMove receipt', text: input.reference || '', files: [file] });
      return 'shared';
    } catch (error) {
      if (error instanceof Error && error.name === 'AbortError') throw error;
      // Unsupported share targets fall through to a normal PDF download.
    }
  }

  const url = URL.createObjectURL(pdf);
  try {
    const link = document.createElement('a');
    link.href = url;
    link.download = filename;
    link.style.display = 'none';
    document.body.appendChild(link);
    link.click();
    link.remove();
  } finally {
    window.setTimeout(() => URL.revokeObjectURL(url), 30_000);
  }
  return 'downloaded';
}
