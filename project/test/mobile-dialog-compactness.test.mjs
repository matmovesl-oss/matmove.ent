import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';

test('receipt and payout dialogs keep close controls compact at narrow mobile widths', async () => {
  const payout = await readFile(new URL('../src/components/PayoutPanel.tsx', import.meta.url), 'utf8');
  const receipt = await readFile(new URL('../src/components/TransactionModal.tsx', import.meta.url), 'utf8');
  const topup = await readFile(new URL('../src/components/WalletTopUp.tsx', import.meta.url), 'utf8');
  const getPaid = await readFile(new URL('../src/components/ReceiveMoneyPanel.tsx', import.meta.url), 'utf8');
  const gala = await readFile(new URL('../src/components/GalaRegistration.tsx', import.meta.url), 'utf8');
  const walletTopUpSource = await readFile(new URL('../src/components/WalletTopUp.tsx', import.meta.url), 'utf8');
  const payoutSource = await readFile(new URL('../src/components/PayoutPanel.tsx', import.meta.url), 'utf8');
  const transactionSource = await readFile(new URL('../src/components/TransactionModal.tsx', import.meta.url), 'utf8');
  assert.match(payout, /shrink-0 whitespace-nowrap rounded-lg border px-3 py-2/);
  assert.match(payout, /max-h-\[calc\(100dvh-1rem\)\].*overscroll-contain/);
  assert.match(receipt, /h-10 w-10 shrink-0 items-center justify-center/);
  assert.match(receipt, /max-h-\[calc\(100dvh-1rem\)\].*overscroll-contain/);
  assert.match(topup, /h-10 w-10 shrink-0 items-center justify-center/);
  assert.ok(getPaid.includes('max-h-[calc(100dvh-1rem)] w-full max-w-lg overflow-y-auto overscroll-contain'));
  assert.match(getPaid, /event.target === event.currentTarget/);
  assert.match(getPaid, /event.key === 'Escape'/);
  assert.match(getPaid, /document.body.style.overflow = 'hidden'/);
  assert.ok(gala.includes('max-h-[calc(100dvh-1.5rem)] w-full max-w-3xl overflow-y-auto overscroll-contain'));
  assert.match(gala, /event.target === event.currentTarget/);
  assert.match(gala, /event.key === 'Escape'/);
  assert.match(gala, /document.body.style.overflow = 'hidden'/);
  assert.match(transactionSource, /event.target === event.currentTarget/);
  assert.match(transactionSource, /event.key === 'Escape'/);
  assert.match(walletTopUpSource, /event.target === event.currentTarget/);
  assert.match(walletTopUpSource, /event.key === 'Escape'/);
  assert.match(walletTopUpSource, /void closeAction.current\(\)/);
  assert.match(payoutSource, /onClick=\{event=>\{if\(event\.target===event\.currentTarget&&!inFlight\.current\)onClose\(\);\}\}/);
});
